/** Preço com a moeda: "R$ 4.990" em português, "1.250 €" em espanhol. O que já tem moeda fica como veio. */
export function comMoeda(valor: string, lang: LangVideo = atual): string {
  const v = (valor || "").trim();
  if (!v) return v;
  if (lang === "es") return /€|eur/i.test(v) ? v : `${v.replace(/^r\$\s*/i, "")} €`;
  return v.startsWith("R$") ? v : "R$ " + v;
}
/** Número do preço, aceitando "R$ 1.990,50" e "1.250 €". */
export const numeroDoPreco = (v: string) => parseFloat((v || "").replace(/[^\d,]/g, "").replace(",", ".")) || 0;
/** Quantidade de parcelas de "10x", "10 x", "10 plazos", "en 6 cuotas"; 0 se não houver. */
export const qtdParcelas = (v: string) => parseInt(((v || "").match(/\d+/) || ["0"])[0], 10) || 0;
/** Número de exemplo do WhatsApp (nunca vai para o vídeo). */
export const whatsExemplo = (lang: LangVideo = atual) => (lang === "es" ? "+34 600 000 000" : "(11) 99999-9999");

