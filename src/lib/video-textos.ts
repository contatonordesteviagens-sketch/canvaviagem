// A chave é o próprio texto em português: com "pt" o texto sai como está escrito no código (nada muda);
// com "es" sai a tradução deste dicionário. Vale para a interface e para o que é desenhado no vídeo.
// Variáveis entram como {nome}: tx("Vídeo {i} de {n}", { i: 1, n: 3 }).

export type LangVideo = "pt" | "es";
type Vars = Record<string, string | number>;

// Idioma do gerador que está na tela. As funções de desenho do vídeo são soltas (fora do React),
// por isso leem daqui; o VideoLabTela define o idioma a cada renderização.
let atual: LangVideo = "pt";
export const setLangVideo = (l: LangVideo) => {
  atual = l;
};
export const langVideo = () => atual;

const aplicar = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);

export function traduzir(lang: LangVideo, pt: string, vars?: Vars): string {
  if (lang !== "es") return aplicar(pt, vars);
  const direto = ES[pt];
  if (direto !== undefined) return aplicar(direto, vars);
  // espaços nas pontas fazem parte do layout (texto colado em outro elemento): traduz só o miolo
  const miolo = pt.trim();
  const es = ES[miolo];
  if (es === undefined) return aplicar(pt, vars);
  const ini = pt.slice(0, pt.length - pt.trimStart().length);
  const fim = pt.slice(pt.trimEnd().length);
  return aplicar(ini + es + fim, vars);
}
/** Tradutor no idioma do gerador que está na tela (interface e desenho do vídeo). */
export const tx = (pt: string, vars?: Vars) => traduzir(atual, pt, vars);
/** Tradutor de um idioma fixo, para os componentes que recebem `lang` por prop. */
export const tradutor = (lang: LangVideo) => (pt: string, vars?: Vars) => traduzir(lang, pt, vars);

/** Devolve o objeto com os campos de texto traduzidos na hora da leitura (para listas fixas do módulo). */
export function comTextos<T extends object>(o: T, campos: (keyof T)[]): T {
  const c = { ...o };
  for (const k of campos) {
    const v = o[k];
    if (typeof v === "string") Object.defineProperty(c, k, { get: () => tx(v), enumerable: true, configurable: true });
  }
  return c;
}

